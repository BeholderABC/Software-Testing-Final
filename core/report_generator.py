# 3. Detailed Test Design & Execution
#    (IEEE 829 Test Design Spec + Test Case Spec + Test Summary Report)
# ---------------------------------------------------------------------------

def _focus_module(reqs: List[Dict[str, Any]],
                  risks: List[Dict[str, Any]]) -> Optional[str]:
    if not reqs:
        return None
    module_by_req = {r.get("requirement_id"): str(r.get("target_module")
                                                   or "General")
                     for r in reqs}
    best_mod, best_score = None, -1.0
    high_count: Dict[str, int] = {}
    for r in risks:
        mod = module_by_req.get(r.get("requirement_id"))
        if mod is None:
            continue
        if _norm_level(r.get("risk_level") or r.get("priority")) == "High":
            high_count[mod] = high_count.get(mod, 0) + 1
        sc = _score(r)
        if sc > best_score or (sc == best_score and high_count.get(mod, 0)
                               > high_count.get(best_mod, 0)):
            best_mod, best_score = mod, sc
    return best_mod or str(reqs[0].get("target_module") or "General")


def _stringify(value: Any, limit: int = 90) -> str:
    text = str(value if not isinstance(value, (dict, list)) else value).strip()
    return text[:limit] + ("…" if len(text) > limit else "")


def generate_detailed_design(requirements: Any, risk: Any, coverage: Any,
                             test_cases: Any, run_summary: Any,
                             meta: Dict[str, Any],
                             runs: Optional[List[Dict[str, Any]]] = None) -> str:
    reqs = _records(requirements)
    risks = _records(risk)
    cov = _records(coverage)
    cases = _records(test_cases)

    module = _focus_module(reqs, risks)
    mod_req_ids = [str(r.get("requirement_id", "?")) for r in reqs
                   if str(r.get("target_module") or "General") == module]
    id_set = set(mod_req_ids)
    feature_by_req = {r.get("requirement_id"): _feature_of(r) for r in reqs}

    out: List[str] = [_provenance(
        meta, f"Detailed Test Design and Execution — {module}")]

    out.append(
        f"\n## 1. Design specification identifier\n\n"
        f"Detailed test design & execution for the **{module}** module, "
        f"run `{meta.get('run_id', '?')}`.")

    out.append(
        "\n## 2. Concept and features to be tested\n\n"
        f"The **{module}** module is the highest-risk component of the "
        "target application (see the Risk Analysis Report). Its rules "
        "co-act, justifying a combination of black-box (EP, BVA, DT) and "
        "white-box (ST) techniques.\n\n"
        "**Table 1.** Requirements served by this module.\n\n"
        + _md_table(["Requirement", "Feature"],
                    [[rid, feature_by_req.get(rid, "—")]
                     for rid in mod_req_ids]))

    mod_cov = [c for c in cov if str(c.get("requirement_id", "")) in id_set]
    out.append(
        "\n## 3. Coverage-item identification\n\n"
        "The coverage engine expands each requirement's constraints into "
        "positive / negative / boundary items.\n\n"
        "**Table 2.** Coverage items for the module.\n\n"
        + _md_table(
            ["Coverage item", "Requirement", "Type", "Strategy"],
            [[_stringify(c.get("coverage_item"), 60),
              c.get("requirement_id", "?"), c.get("coverage_type", "—"),
              c.get("coverage_strategy", "—")] for c in mod_cov]))

    out.append(
        "\n## 4. Coverage strategy and method\n\n"
        "**Table 3.** Coverage type → technique → method.\n\n"
        + _md_table(
            ["Coverage type", "Technique", "Method"],
            [["positive", "Equivalence Partitioning",
              "Submit one valid input; assert acceptance (2xx)."],
             ["negative", "Equivalence Partitioning",
              "Submit one invalid input; assert rejection (4xx)."],
             ["boundary", "Boundary Value Analysis",
              "Sample values on and around each limit."],
             ["combination", "Decision Table Testing",
              "Exercise combinations of co-acting rules."],
             ["state transition", "State Transition Testing (white-box)",
              "Traverse valid transitions and reject invalid guards."]]))

    mod_cases = [c for c in cases
                 if str(c.get("requirement_id", "")) in id_set]
    tech_counts: Dict[str, int] = {}
    box_counts = {"black-box": 0, "white-box": 0}
    case_rows = []
    for c in mod_cases:
        tech = str(c.get("test_design_technique", "—"))
        ctype = str(c.get("coverage_type", "")).lower()
        tech_counts[tech] = tech_counts.get(tech, 0) + 1
        box = ("white-box" if tech == _WHITE_BOX_TECHNIQUE
               else _TYPE_TECHNIQUE.get(ctype, ("", "black-box"))[1])
        box_counts[box] = box_counts.get(box, 0) + 1
        case_rows.append([
            c.get("test_case_id", "?"), tech, c.get("coverage_type", "—"),
            box, _stringify(c.get("description"), 60),
            _stringify(c.get("expected_result"), 50)])
    out.append(
        "\n## 5. Test case specification and coverage\n\n"
        f"The module is covered by **{len(mod_cases)}** test cases — "
        f"{box_counts.get('black-box', 0)} black-box and "
        f"{box_counts.get('white-box', 0)} white-box. Every case traces to "
        "a coverage item in §3.\n\n"
        "**Table 4.** Designed test cases for the module.\n\n"
        + _md_table(
            ["Test case", "Technique", "Coverage type", "Box", "Description",
             "Expected result"], case_rows))
    if tech_counts:
        out.append(
            "\n**Table 5.** Cases by technique.\n\n"
            + _md_table(["Technique", "Cases"],
                        [[t, n] for t, n in sorted(tech_counts.items())],
                        aligns=["l", "r"]))

    out.append(
        "\n## 6. Prompt design and traceability\n\n"
        "The chain *requirement → coverage item → test case → executing "
        "function* is fully reconstructable through each case's "
        "`traceability` block. The LLM stages (parsing, risk) are "
        "schema-constrained and run at `temperature=0`, so the structured "
        "inputs are reproducible.")

    out.append("\n## 7. Result analysis (Test Summary Report)\n")
    out.append(_modes_section(runs or []))
    out.append(_result_section(run_summary, id_set))

    out.append(
        "\n## 8. Evidence-based improvement and designer involvement\n\n"
        "Each failing case traces to one requirement and one coverage "
        "item, localising the defect class the technique exposed. The "
        "designer may revise coverage items, strategies and cases "
        "interactively in the tool; each edit invalidates downstream "
        "artefacts, which regenerate, so the suite always reflects the "
        "latest decisions.")

    out.append(
        "\n## References\n\n"
        "- IEEE 829-2008, *Standard for Software and System Test "
        "Documentation*.\n"
        "- ISO/IEC/IEEE 29119-4:2021, *Test techniques*.\n"
        "- ISTQB, *Foundation Level Syllabus*, 2018.\n")
    return "\n".join(out) + "\n"


_HTTP_MODE_LABEL = {"dedup": "representative-per-key",
                    "full": "individual (full)"}


def _modes_section(runs: List[Dict[str, Any]]) -> str:
    if not runs:
        return ""

    def _g(summary: Any, name: str, default: Any = 0) -> Any:
        return getattr(summary, name, default)

    rows = []
    for r in runs:
        s = r.get("summary")
        rows.append([
            r.get("source", "—"),
            _HTTP_MODE_LABEL.get(r.get("http_mode"), r.get("http_mode", "—")),
            r.get("generated_count", "—"), r.get("executed_count", "—"),
            _g(s, "passed"), _g(s, "failed"), _g(s, "skipped"),
            round(float(_g(s, "duration_seconds", 0.0)), 2)])
    note = ""
    if any(r.get("http_mode") == "dedup" for r in runs) and \
            any(r.get("http_mode") == "full" for r in runs):
        note = (
            "\n\nThe deduplicated and full-individual runs report the same "
            "pass/fail verdict, confirming that representative-per-key "
            "execution covers the same observable behaviour as executing "
            "every case.")
    return (
        "\n**Table 6.** Execution outcome by run mode (source × HTTP "
        "execution).\n\n"
        + _md_table(
            ["Source", "HTTP execution", "Designed", "Executed", "Passed",
             "Failed", "Skipped", "Seconds"], rows,
            aligns=["l", "l", "r", "r", "r", "r", "r", "r"]) + note)


def _result_section(run_summary: Any, id_set: set) -> str:
    results = _run_results(run_summary)
    if not results:
        return ("\n_The suite has not yet been executed for this run. Run "
                "the tests (Step 8) and regenerate this report to populate "
                "the execution results._")

    def _attr(obj: Any, name: str, default: Any = "") -> Any:
        if isinstance(obj, dict):
            return obj.get(name, default)
        return getattr(obj, name, default)

    rows, passed, failed = [], 0, 0
    for r in results:
        rid = str(_attr(r, "requirement_id"))
        if id_set and rid not in id_set:
            continue
        outcome = str(_attr(r, "outcome", "")).lower()
        if outcome == "passed":
            passed += 1
        elif outcome in ("failed", "error"):
            failed += 1
        rows.append([_attr(r, "test_case_id", "?"), rid,
                     _attr(r, "coverage_type", "—"), outcome.upper() or "—",
                     _stringify(_attr(r, "message"), 60)])
    total = getattr(run_summary, "total", None)
    duration = getattr(run_summary, "duration_seconds", None)
    header = (f"\nThe canonical run reported **{passed} passed**, "
              f"**{failed} failed** for this module")
    if total is not None:
        header += f" (suite total {total}"
        if duration is not None:
            header += f", {round(float(duration), 2)} s"
        header += ")"
    header += ".\n"
    return (header + "\n**Table 7.** Per-case execution outcome (canonical "
            "run).\n\n" + _md_table(
                ["Test case", "Requirement", "Coverage type", "Outcome",
                 "Message"], rows))


# ---------------------------------------------------------------------------
# Rule-only entry point (used directly by tests / offline scripts; the
# live orchestrator in core/report_pipeline.py calls the three generators
# individually so it can mix LLM and rule output per document).
# ---------------------------------------------------------------------------

def generate_all(requirements: Any, risk: Any, coverage: Any,
                 test_cases: Any, docs_dir: str,
                 test_summary: Optional[Dict[str, Any]] = None,
                 optimization_summary: Optional[Dict[str, Any]] = None,
                 run_summary: Any = None,
                 runs: Optional[List[Dict[str, Any]]] = None,
                 pipeline_timings: Optional[List[Dict[str, Any]]] = None,
                 meta: Optional[Dict[str, Any]] = None) -> Dict[str, str]:
    """Render all three reports with the rule engine and write them.

    Note: the ``METRICS_MARKER`` is left in place here; the orchestrator
    is responsible for replacing it. When used standalone (tests), the
    marker simply remains as an HTML comment.
    """
    os.makedirs(docs_dir, exist_ok=True)
    meta = dict(meta or {})
    meta.setdefault("generated_at",
                    datetime.now().strftime("%Y-%m-%d %H:%M:%S"))

    documents = {
        "risk_analysis_report": (
            "risk_analysis_report.md",
            generate_risk_analysis_report(requirements, risk, meta)),
        "test_plan": (
            "test_plan.md",
            generate_test_plan(requirements, risk, coverage, test_cases,
                               test_summary, optimization_summary, runs, meta,
                               pipeline_timings)),
        "detailed_test_design_execution": (
            "detailed_test_design_execution.md",
            generate_detailed_design(requirements, risk, coverage, test_cases,
                                     run_summary, meta, runs)),
    }
    paths: Dict[str, str] = {}
    for key, (filename, content) in documents.items():
        path = os.path.join(docs_dir, filename)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        paths[key] = path
    return paths
