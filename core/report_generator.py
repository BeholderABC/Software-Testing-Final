def _run_results(run_summary: Any) -> List[Any]:
    """Extract the per-case result list from a ``RunSummary`` object or an
    equivalent dict, leaving each element in its native form (the
    elements are ``TestResult`` dataclasses, not dicts)."""
    if run_summary is None:
        return []
    results = getattr(run_summary, "results", None)
    if results is None and isinstance(run_summary, dict):
        results = run_summary.get("results")
    return list(results or [])


def _records(data: Any) -> List[Dict[str, Any]]:
    """Coerce a DataFrame / list-of-dicts / None into a list of dicts."""
    if data is None:
        return []
    to_dict = getattr(data, "to_dict", None)
    if callable(to_dict) and hasattr(data, "columns"):  # pandas DataFrame
        return data.to_dict(orient="records")
    if isinstance(data, list):
        return [r for r in data if isinstance(r, dict)]
    if isinstance(data, dict):
        for key in ("test_cases", "optimized_test_cases", "coverages"):
            inner = data.get(key)
            if isinstance(inner, list):
                return [r for r in inner if isinstance(r, dict)]
    return []


def _md_table(headers: Sequence[str], rows: Sequence[Sequence[Any]],
              *, aligns: Optional[Sequence[str]] = None,
              empty: str = "_No data for this run._") -> str:
    """Render a GitHub-flavoured Markdown table. ``aligns`` entries are
    'l' | 'c' | 'r'; defaults to left."""
    if not rows:
        return empty
    sep_map = {"l": "---", "c": ":---:", "r": "---:"}
    seps = [sep_map.get((aligns or [])[i] if aligns and i < len(aligns)
                        else "l", "---") for i in range(len(headers))]

    def _cell(v: Any) -> str:
        return str(v).replace("\n", " ").replace("|", "\\|")

    lines = ["| " + " | ".join(_cell(h) for h in headers) + " |",
             "| " + " | ".join(seps) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(_cell(c) for c in row) + " |")
    return "\n".join(lines)


def _provenance(meta: Dict[str, Any], doc_title: str) -> str:
    """Standard provenance banner placed at the top of every report."""
    run_id = meta.get("run_id", "run_<unknown>")
    when = meta.get("generated_at") or datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S")
    target = meta.get("target_app", DEFAULT_TARGET_APP)
    engine = meta.get("engine_source", "rule pipeline")
    return (
        f"# {doc_title}\n\n"
        f"> _Auto-generated by **AutoTestDesign** (rule engine) for run "
        f"`{run_id}` on {when}._\n"
        f"> _Target application: **{target}**. Design engine: {engine}._\n")


def _norm_level(value: Any) -> str:
    s = str(value or "").strip().lower()
    if s.startswith("high"):
        return "High"
    if s.startswith("med"):
        return "Medium"
    if s.startswith("low"):
        return "Low"
    return str(value or "—")


def _score(rec: Dict[str, Any]) -> float:
    try:
        return float(rec.get("risk_score", 0) or 0)
    except (TypeError, ValueError):
        return 0.0


def _feature_of(rec: Dict[str, Any]) -> str:
    """Best available short description of a requirement."""
    for key in ("feature", "raw_requirement", "expected_action",
                "target_module"):
        val = rec.get(key)
        if val:
            text = str(val).strip()
            return text[:70] + ("…" if len(text) > 70 else "")
    return "—"


def _timings_table(pipeline_timings: Optional[List[Dict[str, Any]]]) -> str:
    """Render the tool-measured design-phase pipeline timings."""
    rows = [[t.get("stage", "—"), t.get("engine", "—"),
             round(float(t.get("seconds", 0) or 0), 3)]
            for t in (pipeline_timings or [])]
    if not rows:
        return "_No pipeline timings were recorded for this run._"
    total = round(sum(r[2] for r in rows), 3)
    rows.append(["**Total**", "", total])
    return _md_table(["Stage", "Engine", "Seconds"], rows,
                     aligns=["l", "l", "r"])


