"""
report_generator.py  --  Deterministic (rule) Markdown report generator.

This is the **fallback** path for the three deliverable documents. When a
language model is configured the documents are written by
``core/report_llm.py``; when it is absent or a call fails, the
orchestrator (``core/report_pipeline.py``) falls back here so generation
always completes offline.

Both paths emit the *same IEEE 829 section structure*, so a reader cannot
tell design-time which engine produced a given document beyond the
provenance banner and the tool-measured generation-metrics block. Every
table, count and classification is filled from the current run's data;
nothing is invented. Inputs are accepted as pandas DataFrames or plain
lists of dicts, and every field access is defensive.

The hand-authored documents under the repository ``docs/`` directory
remain the gold reference; files produced here live under
``outputs/run_<ts>/docs/``.
"""

from __future__ import annotations

import os
from datetime import datetime
from typing import Any, Dict, List, Optional, Sequence

# Default identity of the target application. Overridable through ``meta``.
DEFAULT_TARGET_APP = "Mini-E-Commerce Backend (Django REST)"

# Replaced post-generation by the orchestrator with the tool-measured
# document-generation time + token usage (see core/report_pipeline.py).
# Both the LLM prompts and this rule generator emit it verbatim, so the
# same injection works regardless of which engine produced the document.
METRICS_MARKER = "<!-- AUTOTESTDESIGN_METRICS -->"

