def generate_risk_analysis_report(requirements: Any, risk: Any,
                                  meta: Dict[str, Any]) -> str:
    reqs = _records(requirements)
    risks = _records(risk)
    feature_by_req = {r.get("requirement_id"): _feature_of(r) for r in reqs}
    target = meta.get("target_app", DEFAULT_TARGET_APP)

    register = sorted(risks, key=_score, reverse=True)
    counts = {"High": 0, "Medium": 0, "Low": 0}
    by_level: Dict[str, List[str]] = {"High": [], "Medium": [], "Low": []}
    for r in risks:
        lvl = _norm_level(r.get("risk_level") or r.get("priority"))
        if lvl in counts:
            counts[lvl] += 1
            by_level[lvl].append(str(r.get("requirement_id", "?")))

    out: List[str] = [_provenance(meta, f"Risk Analysis Report — {target}")]

    out.append(
        f"\n## 1. Report identifier\n\n"
        f"Risk Analysis Report for run `{meta.get('run_id', '?')}`, "
        f"concerning the **target application** ({target}) — not the "
        "AutoTestDesign tool.")

    out.append(
        "\n## 2. Introduction\n\n"
        f"This report rates the **{len(risks)}** catalogued requirements of "
        "the target application by product risk so that test effort can be "
        "concentrated where a defect is both likely and damaging "
        "(ISTQB 2018; ISO/IEC/IEEE 29119-1). The risk level of each "
        "requirement governs its coverage depth downstream.")

    out.append(
        "\n## 3. Risk assessment method\n\n"
        "Each requirement is rated 1–3 on four dimensions — "
        "`business_impact`, `failure_probability`, `complexity`, "
        "`failure_impact`. The four ratings (sum 4–12) are linearly "
        "rescaled to a 1–10 `risk_score`, mapped to a level: 1–3 Low, "
        "4–7 Medium, 8–10 High.")

    reg_rows = [
        [r.get("requirement_id", "?"),
         feature_by_req.get(r.get("requirement_id"), "—"),
         _norm_level(r.get("risk_level") or r.get("priority")),
         r.get("risk_score", "—")]
        for r in register]
    out.append(
        "\n## 4. Risk register\n\n"
        "**Table 1.** Requirements ordered by descending risk score.\n\n"
        + _md_table(["Requirement", "Feature", "Level", "Score"], reg_rows,
                    aligns=["l", "l", "l", "r"]))

    dist_rows = [[lvl, counts[lvl], ", ".join(by_level[lvl]) or "—"]
                 for lvl in ("High", "Medium", "Low")]
    out.append(
        "\n## 5. Risk distribution\n\n"
        "**Table 2.** Count of requirements per risk level.\n\n"
        + _md_table(["Level", "Count", "Requirements"], dist_rows,
                    aligns=["l", "r", "l"])
        + "\n\n```mermaid\npie showData\n    title Risk level distribution\n"
        + f"    \"High\" : {counts['High']}\n"
        + f"    \"Medium\" : {counts['Medium']}\n"
        + f"    \"Low\" : {counts['Low']}\n```")

    out.append("\n## 6. High-risk items\n")
    highs = [r for r in register
             if _norm_level(r.get("risk_level") or r.get("priority")) == "High"]
    if not highs:
        out.append("\n_No requirement reached the High band in this run._")
    else:
        for r in highs:
            rid = r.get("requirement_id", "?")
            out.append(
                f"\n### 6.{highs.index(r) + 1} {rid} — "
                f"{feature_by_req.get(rid, '')} (score {r.get('risk_score', '—')})\n\n"
                f"- Dimensions — business_impact {r.get('business_impact', '—')}, "
                f"failure_probability {r.get('failure_probability', '—')}, "
                f"complexity {r.get('complexity', '—')}, "
                f"failure_impact {r.get('failure_impact', '—')}.")
            if r.get("risk_reason"):
                out.append(f"- Rationale — {r.get('risk_reason')}")
            out.append(
                "- Test focus — favour boundary, negative and "
                "decision-table cases on this requirement.")

    out.append(
        "\n## 7. Risk-to-coverage strategy\n\n"
        "**High** retains every generated case and favours boundary, "
        "negative and decision-table cases; **Medium** keeps one "
        "representative per coverage type plus all decision-table cases; "
        "**Low** deduplicates by coverage type, always keeping at least "
        "one case. The deepest coverage therefore falls on the High-risk "
        "items above.")

    out.append(
        "\n## 8. Mitigation recommendations\n\n"
        + _md_table(
            ["Area", "Recommendation"],
            [[feature_by_req.get(r.get("requirement_id"),
                                 r.get("requirement_id", "?")),
              "Prioritise deep coverage; review the guard/transaction "
              "logic that drives its High rating."]
             for r in highs] or [["—", "No High-risk areas in this run."]]))

    out.append(
        "\n## 9. Limitations and approvals\n\n"
        "The ratings are model-derived judgements, made reproducible by a "
        "fixed combination rule and overridable by the tester before the "
        "suite is designed.\n")

    out.append(
        "\n## References\n\n"
        "- ISO/IEC/IEEE 29119-1:2022, *Software testing — Part 1*.\n"
        "- IEEE 829-2008, *Standard for Software and System Test "
        "Documentation*.\n"
        "- ISTQB, *Foundation Level Syllabus*, 2018.\n")
    return "\n".join(out) + "\n"


