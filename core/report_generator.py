def _module_index(reqs: List[Dict[str, Any]]) -> Dict[str, List[str]]:
    index: Dict[str, List[str]] = {}
    for r in reqs:
        mod = str(r.get("target_module") or "General")
        index.setdefault(mod, []).append(str(r.get("requirement_id", "?")))
    return index


def _techniques_for_reqs(cases: List[Dict[str, Any]],
                         req_ids: Sequence[str]) -> List[str]:
    wanted = set(req_ids)
    techs: List[str] = []
    for c in cases:
        if str(c.get("requirement_id", "")) in wanted:
            tech = str(c.get("test_design_technique", "")).strip()
            if tech and tech not in techs:
                techs.append(tech)
    return techs


def generate_test_plan(requirements: Any, risk: Any, coverage: Any,
                       test_cases: Any, test_summary: Optional[Dict[str, Any]],
                       optimization_summary: Optional[Dict[str, Any]],
                       runs: Optional[List[Dict[str, Any]]],
                       meta: Dict[str, Any],
                       pipeline_timings: Optional[List[Dict[str, Any]]] = None
                       ) -> str:
    reqs = _records(requirements)
    risks = _records(risk)
    cov = _records(coverage)
    cases = _records(test_cases)
    target = meta.get("target_app", DEFAULT_TARGET_APP)

    level_by_req = {
        r.get("requirement_id"): _norm_level(
            r.get("risk_level") or r.get("priority")) for r in risks}
    modules = _module_index(reqs)
    n_cases = (test_summary or {}).get("total", len(cases))

    out: List[str] = [_provenance(meta, f"Test Plan — {target}")]

    out.append(
        f"\n## 1. Test plan identifier\n\n"
        f"Master Test Plan for run `{meta.get('run_id', '?')}`, covering "
        f"the **target application** ({target}).")

    out.append(
        "\n## 2. Introduction\n\n"
        f"This plan governs verification of the target application using "
        f"AutoTestDesign, which structured **{len(reqs)}** requirements, "
        f"derived **{len(cov)}** coverage items and generated "
        f"**{n_cases}** test cases. Objectives: verify the requirements "
        "against the running system; concentrate effort on higher-risk "
        "requirements (see the Risk Analysis Report); execute the "
        "tool-produced artefacts directly without manual transcription; "
        "and detect, repair and re-verify defects. The process has two "
        "layers — AutoTestDesign designs the artefacts, PyTest executes "
        "them.")

    item_rows = []
    for mod, ids in modules.items():
        levels = sorted({level_by_req.get(i, "—") for i in ids})
        item_rows.append([mod, ", ".join(ids), " / ".join(levels) or "—"])
    out.append(
        "\n## 3. Test items\n\n"
        "**Table 1.** Components under test.\n\n"
        + _md_table(["Component / module", "Requirements", "Risk levels"],
                    item_rows))

    out.append(
        "\n## 4. Features to be tested\n\n"
        "All catalogued functional requirements above are in scope. "
        "Non-functional attributes evaluated: **performance** (generation "
        "latency), **usability** (the guided Streamlit workflow), "
        "**security** (negative cases assert 4xx rejection), and "
        "**maintainability** (deterministic engines, unit-tested).")

    out.append(
        "\n## 5. Features not to be tested\n\n"
        "Any behaviour not covered by a catalogued requirement, plus "
        "production-scale load/stress testing and deployment, are out of "
        "scope for this plan.")

    suite_rows = []
    for mod, ids in modules.items():
        techs = _techniques_for_reqs(cases, ids) or ["—"]
        levels = sorted({level_by_req.get(i, "—") for i in ids})
        suite_rows.append([mod, ", ".join(ids), " / ".join(levels) or "—",
                           ", ".join(techs),
                           "Depth set by risk level; techniques chosen per "
                           "constraint structure."])
    out.append(
        "\n## 6. Approach (high-level test suite design)\n\n"
        "Suites are organised by component; techniques follow the "
        "ISO/IEC/IEEE 29119-4 vocabulary (EP, BVA, DT, ST), selected from "
        "risk level and constraint structure.\n\n"
        "**Table 2.** Suite-level design.\n\n"
        + _md_table(["Suite", "Requirements", "Risk level", "Techniques",
                     "Rationale"], suite_rows))

    out.append(
        "\n## 7. Item pass/fail criteria\n\n"
        "An item passes when the observed response/state matches its "
        "synthesised oracle (expected status and payload assertions); "
        "otherwise it fails and is logged for repair.")

    out.append(
        "\n## 8. Suspension and resumption criteria\n\n"
        "Execution is suspended if the backend is unreachable or the unit "
        "suite is red, and resumes once both are restored.")

    out.append(
        "\n## 9. Test deliverables\n\n"
        "Data artefacts (CSV / JSON / Excel) in `data/`, and the three "
        "Markdown reports (this plan, the risk analysis report, the "
        "detailed test design & execution) in `docs/`.")

    # 10. Tasks, schedule, cost.
    executed = bool(runs)
    out.append(
        "\n## 10. Testing tasks, schedule and cost\n\n"
        "### 10.1 Test levels and schedule\n\n"
        "**Table 3.** Test levels and objectives.\n\n"
        + _md_table(
            ["Level", "Objective", "Location"],
            [["Unit", "Verify the tool's internal engines", "`tests/unit/`"],
             ["Integration",
              "Execute tool-produced artefacts against the live backend",
              "`tests/integration/`"],
             ["System", "End-to-end backend behaviour",
              "`tests/integration/` (hand-written)"]])
        + "\n\n**Table 4.** Phase checklist.\n\n"
        + _md_table(
            ["Phase", "Activity", "Status"],
            [["Planning", "Scope, risk ranking, framework selection", "☑"],
             ["Design", "Parsing, coverage, test-case generation", "☑"],
             ["Implementation", "PyTest harness and data-driven adapter",
              "☑"],
             ["Execution", "Run all suites against the backend",
              "☑" if executed else "☐"],
             ["Reporting", "Traceability, documentation, packaging", "☐"]]))
    out.append(_cost_section(len(reqs), n_cases, optimization_summary,
                             pipeline_timings))

    out.append(
        "\n## 11. Environmental needs and chosen framework\n\n"
        "**Table 6.** Frameworks selected to execute tests on the target "
        "application.\n\n"
        + _md_table(
            ["Framework", "Used for", "Rationale"],
            [["PyTest", "Test execution",
              "Python de-facto standard; `parametrize` drives the "
              "data-driven harness; readable reports."],
             ["`requests`", "HTTP calls to the backend",
              "Simple, explicit; mirrors a real REST client."],
             ["Django REST Framework", "The system under test",
              "The framework the target application is built on."],
             ["Streamlit", "The tool's UI",
              "Interactive editable tables for human-in-the-loop review."]])
        + "\n\nSelenium and JUnit were considered and rejected: the target "
          "is a REST backend with no browser layer, so HTTP-level testing "
          "with `requests`+PyTest is more direct, and JUnit does not apply "
          "to a Python/Django stack. The backend runs locally on the URL "
          "given in the sidebar.")

    out.append(
        "\n## 12. Responsibilities and staffing\n\n"
        "**Table 7.** Roles and responsibilities.\n\n"
        + _md_table(
            ["Role", "Responsibilities"],
            [["Test lead", "Plan ownership, risk sign-off, scheduling"],
             ["Tool / pipeline",
              "Parsing, risk, coverage and test-design engines"],
             ["User interface", "Streamlit workflow, export, in-UI runner"],
             ["Target application",
              "Backend, PyTest harness, defect repair and re-test"],
             ["Documentation", "Reports, traceability, packaging"]])
        + "\n\n```mermaid\nflowchart TD\n    Lead[Test lead]\n"
          "    Lead --> Pipeline[Tool / pipeline]\n"
          "    Lead --> UI[User interface]\n"
          "    Lead --> Target[Target application]\n"
          "    Lead --> Docs[Documentation]\n```")

    high_ids = [str(r.get("requirement_id", "?")) for r in risks
                if _norm_level(r.get("risk_level") or r.get("priority"))
                == "High"]
    out.append(
        "\n## 13. Risks and contingencies\n\n"
        "Product risk is detailed in the Risk Analysis Report. The "
        f"High-risk requirements requiring the deepest coverage are: "
        f"{', '.join(high_ids) or 'none in this run'}.")

    out.append(
        "\n## References\n\n"
        "- IEEE 829-2008, *Standard for Software and System Test "
        "Documentation*.\n"
        "- ISO/IEC/IEEE 29119-4:2021, *Test techniques*.\n"
        "- ISTQB, *Foundation Level Syllabus*, 2018.\n")
    return "\n".join(out) + "\n"


def _cost_section(n_reqs: int, n_cases: int,
                  optimization_summary: Optional[Dict[str, Any]],
                  pipeline_timings: Optional[List[Dict[str, Any]]]) -> str:
    """Cost estimation: a manual-vs-tool effort estimate, the measured
    design-phase pipeline timings, and the metrics marker the orchestrator
    replaces with measured generation time + token usage."""
    manual_minutes_per_case = 20
    manual_hours = round(n_cases * manual_minutes_per_case / 60.0, 1)
    tool_review_minutes_per_req = 5
    tool_hours = round(n_reqs * tool_review_minutes_per_req / 60.0, 1)
    saved = round(manual_hours - tool_hours, 1)
    opt_note = ""
    if optimization_summary:
        opt_note = (
            f" Risk-based optimisation reduced the executable set from "
            f"{optimization_summary.get('original_count', '—')} to "
            f"{optimization_summary.get('optimized_count', '—')} cases "
            f"(strategy: {optimization_summary.get('strategy', '—')}).")
    return (
        "\n### 10.2 Cost estimation\n\n"
        f"Effort is estimated from this run's volume — **{n_reqs}** "
        f"requirements and **{n_cases}** generated test cases.\n\n"
        "**Table 5a.** Effort comparison (person-hours).\n\n"
        + _md_table(
            ["Approach", "Basis", "Estimated effort"],
            [["Manual design & scripting",
              f"{n_cases} cases × {manual_minutes_per_case} min",
              f"≈ {manual_hours} h"],
             ["AutoTestDesign (review only)",
              f"{n_reqs} req × {tool_review_minutes_per_req} min review + "
              "~0 generation", f"≈ {tool_hours} h"],
             ["Saving", "manual − tool", f"≈ {saved} h"]],
            aligns=["l", "l", "r"])
        + "\n\nThe marginal per-project design+execution cost approaches "
          "zero." + opt_note
        + "\n\n**Table 5b.** Measured design-phase pipeline timings "
          "(tool-instrumented, wall-clock).\n\n"
        + _timings_table(pipeline_timings)
        + "\n\n**Document generation metrics** (model-call time and token "
          "usage, tool-measured):\n\n" + METRICS_MARKER)


